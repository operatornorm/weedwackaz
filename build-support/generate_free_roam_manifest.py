#!/usr/bin/env python3
"""Generate data-only Lua from pinned allocation inputs; no game-install access."""

import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from expand_free_roam_allocation import make_support_pack
from plan_free_roam_allocation import MANIFEST, FREE_ROAM_SUPPORT, read_json, staged_package_paths


def build_data(source):
    pins = read_json(MANIFEST)
    support = make_support_pack((source / "moddata/coop_essentials/coop_essentials.fpkd").read_bytes(),
                                pins["support_source_sha256"])
    result = {"schema": 1, "executable_sha256": pins["executable_sha256"],
              "support_fpk": FREE_ROAM_SUPPORT,
              "support_fpkd_sha256": hashlib.sha256(support).hexdigest(), "targets": []}
    for target in pins["targets"]:
        result["targets"].append({
            "id": target["id"], "mission": target["mission"],
            "location": 10 if target["mission"] == 30010 else 20,
            "branch": "recoverVolginDemo" if target["id"] == "afghanistan-recover-volgin" else "normal",
            "source_fpk": target["loader_pack"], "source_loader_sha256": target["loader_pack_sha256"],
            "source_fpkd_sha256": target["package_sha256"], "profile_hash": target["parts_profile_hash"],
            "staged_fpk": staged_package_paths(target["id"])[0],
            "staged_fpkd": staged_package_paths(target["id"])[1],
        })
    result["manifest_sha256"] = hashlib.sha256(json.dumps(result, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    return result


def lua(value, indent=0):
    if isinstance(value, str):
        return json.dumps(value)
    if type(value) is int:
        return str(value)
    items = enumerate(value, 1) if isinstance(value, list) else value.items()
    rows = []
    for key, item in items:
        label = "" if isinstance(value, list) else "[" + json.dumps(key) + "] = "
        rows.append(" " * (indent + 4) + label + lua(item, indent + 4) + ",")
    return "{\n" + "\n".join(rows) + "\n" + " " * indent + "}"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT.parent / "dynamite")
    args = parser.parse_args()
    data = build_data(args.source)
    output = args.source / "moddata/standalone/WWFreeRoamManifest.lua"
    output.write_text("-- Generated by build-support/generate_free_roam_manifest.py. Data only; never enables co-op.\nreturn " + lua(data) + "\n")
    print("Generated dormant Free Roam manifest", data["manifest_sha256"])


if __name__ == "__main__":
    main()

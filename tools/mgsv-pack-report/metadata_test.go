func TestQARVersionsCompressionAndInnerEncryption(t *testing.T) {
	payload := syntheticFPK(map[string][]byte{allocationName: bytes.Repeat([]byte("synthetic"), 100)}, nil)
	for _, version := range []uint32{1, 2} {
		for _, compressed := range []bool{false, true} {
			for _, encrypted := range []bool{false, true} {
				data := syntheticQAR(t, version, compressed, encrypted, payload)
				gotVersion, entries, err := indexArchive(bytes.NewReader(data), int64(len(data)))
				if err != nil || gotVersion != version || len(entries) != 1 {
					t.Fatalf("index: %d %v", gotVersion, err)
				}
				decoded, stage, err := decodeContainer(bytes.NewReader(data), version, entries[0])
				if err != nil {
					t.Fatalf("v%d compressed=%v encrypted=%v: %v", version, compressed, encrypted, err)
				}
				if !bytes.Equal(decoded, payload) {
					t.Fatal("decoded container differs")
				}
				if stage != "both" && stage != "decrypted_stored" {
					t.Fatal("writer digest stage not identified", stage)
				}
				if version == 2 {
					for _, half := range []int{0, 8} {
						bad := entries[0]
						bad.checksum[half] ^= 1
						_, _, err := decodeContainer(bytes.NewReader(data), version, bad)
						if err == nil {
							t.Fatal("altered digest half accepted", half)
						}
						if half != int((bad.hash&1)*8) && err.Error() != "container_checksum_mismatch" {
							t.Fatal("unselected digest half was not fully verified", err)
						}
					}
				}
			}
		}
	}
}


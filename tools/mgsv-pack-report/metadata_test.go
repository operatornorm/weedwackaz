// These fixtures predate this tool and were not generated by datfpk's writer.
// The .dat pair is documented upstream as GzsTool-produced. The compressed
// entry fragment has a separately supplied decoded FPK for byte comparison.
func TestPinnedUpstreamQARDigestConventions(t *testing.T) {
	base := filepath.Join(pinnedDatfpkDirectory(t), "qar/testdata")
	script, err := filepath.Abs(filepath.Join("..", "mgsv_pack_report.py"))
	if err != nil {
		t.Fatal(err)
	}
	for _, fixture := range []struct{ name, expected, kind, stage string }{
		{"plain.dat", "", "archive", "both"},
		{"compressed.dat", "compressed_dat/test.lua", "archive", "decoded_payload"},
		{"foxdat", "foxpatch.dat", "fragment", "decrypted_stored"},
		{"plfova_cmf0_main0_def_v00.fpk.compressed", "plfova_cmf0_main0_def_v00.fpk", "fragment", "decoded_payload"},
	} {
		t.Run(fixture.name, func(t *testing.T) {
			file, expectedFile := filepath.Join(base, fixture.name), filepath.Join(base, fixture.expected)
			data, err := os.ReadFile(file)
			if err != nil {
				t.Fatal(err)
			}
			var expected []byte
			if fixture.name == "plain.dat" {
				// Upstream qar_test.go:TestQar_ExtractTo supplies this literal;
				// plain_dat/test.lua is a different writer-input fixture.
				expected = []byte("data1234567890\n")
				expectedFile = filepath.Join(t.TempDir(), "expected")
				if err := os.WriteFile(expectedFile, expected, 0600); err != nil {
					t.Fatal(err)
				}
			} else {
				expected, err = os.ReadFile(expectedFile)
				if err != nil {
					t.Fatal(err)
				}
			}
			version, entry := uint32(1), archiveEntry{}
			if fixture.kind == "archive" {
				v, entries, err := indexArchive(bytes.NewReader(data), int64(len(data)))
				if err != nil || len(entries) != 1 {
					t.Fatalf("fixture index: %v", err)
				}
				version, entry = v, entries[0]
			} else {
				entry.hash, entry.offset = le.Uint64(data)^0x4144104341441043, 32
				entry.stored, entry.decoded = le.Uint32(data[8:])^0x11c22050, le.Uint32(data[12:])^0xd05608c3
				copy(entry.checksum[:], data[16:32])
				entry.checksum, err = qar.Md5Decode(entry.checksum)
				if err != nil {
					t.Fatal(err)
				}
			}
			got, stage, err := decodeContainer(bytes.NewReader(data), version, entry)
			if err != nil || !bytes.Equal(got, expected) || stage != fixture.stage {
				t.Fatalf("independent decode/digest: stage=%s err=%v", stage, err)
			}
			entry.checksum = qar.Md5Sum{}
			if _, _, err := decodeContainer(bytes.NewReader(data), version, entry); err == nil || err.Error() != "container_checksum_mismatch" {
				t.Fatal("invalid digest was not rejected", err)
			}
			code := "import sys,importlib.util,io,struct\nfrom pathlib import Path\n" +
				"spec=importlib.util.spec_from_file_location('r',sys.argv[1]);r=importlib.util.module_from_spec(spec);spec.loader.exec_module(r)\n" +
				"b=Path(sys.argv[2]).read_bytes();expected=Path(sys.argv[3]).read_bytes()\n" +
				"if sys.argv[4]=='archive':\n v,entries=r.index_archive(io.BytesIO(b),len(b));e=entries[0]\n" +
				"else:\n v=1;e=(r.get64(b,0)^0x4144104341441043,32,r.get32(b,8)^r.XOR[1],r.get32(b,12)^r.XOR[2],struct.pack('<4I',*(r.get32(b,16+j*4)^m for j,m in enumerate((r.XOR[3],r.XOR[0],r.XOR[0],r.XOR[1])))),0)\n" +
				"verification={};assert r.decode(io.BytesIO(b),len(b),v,e,verification)==expected;assert verification['checksum_stage']==sys.argv[5]\n" +
				"bad=list(e);bad[4]=bytes(16)\ntry: r.decode(io.BytesIO(b),len(b),v,bad)\nexcept r.ReportError as ex: assert str(ex)=='container_checksum_mismatch'\nelse: raise AssertionError('invalid digest accepted')\n"
			output, err := exec.Command("python3", "-c", code, script, file, expectedFile, fixture.kind, fixture.stage).CombinedOutput()
			if err != nil {
				t.Fatalf("Python external fixture: %v\n%s", err, output)
			}
		})
	}
}

func TestStoredDigestCannotBypassZlibValidation(t *testing.T) {
	data := syntheticQAR(t, 1, true, false, syntheticFPK(nil, nil))
	_, entries, err := indexArchive(bytes.NewReader(data), int64(len(data)))
	if err != nil {
		t.Fatal(err)
	}
	entry := entries[0]
	first := qar.Decrypt1Stream{}
	first.Init(entry.checksum, entry.hash, 1, int(entry.stored))
	raw, err := first.Read(bytes.NewReader(data[entry.offset:]), int(entry.stored))
	if err != nil {
		t.Fatal(err)
	}
	for _, kind := range []string{"adler32", "truncated", "trailing", "second_stream", "decoded_length"} {
		t.Run(kind, func(t *testing.T) {
			plain, bad := append([]byte{}, raw...), entry
			switch kind {
			case "adler32":
				plain[len(plain)-1] ^= 1
			case "truncated":
				plain = plain[:len(plain)-1]
			case "trailing":
				plain = append(plain, 'x')
			case "second_stream":
				plain = append(plain, raw...)
			case "decoded_length":
				bad.decoded++
			}
			bad.stored, bad.offset = uint32(len(plain)), 0
			bad.checksum = qar.Md5Sum(md5.Sum(plain))
			outer := qar.Decrypt1Stream{}
			outer.Init(bad.checksum, bad.hash, 1, len(plain))
			encoded, err := outer.Read(bytes.NewReader(plain), len(plain))
			if err != nil {
				t.Fatal(err)
			}
			if _, _, err := decodeContainer(bytes.NewReader(encoded), 1, bad); err == nil {
				t.Fatal("matching stored digest bypassed malformed stream/length", kind)
			}
		})
	}
}


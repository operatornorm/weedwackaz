func syntheticFPK(members map[string][]byte, refs []string) []byte {
	names := []string{}
	for name := range members {
		names = append(names, name)
	}
	sort.Strings(names)
	data := make([]byte, 48+48*len(names)+16*len(refs))
	copy(data, fpk.MagicFpkd[:])
	le.PutUint32(data[32:], 2)
	le.PutUint32(data[36:], uint32(len(names)))
	le.PutUint32(data[40:], uint32(len(refs)))
	for i, name := range names {
		row := data[48+48*i:]
		le.PutUint32(row[16:], uint32(len(data)))
		le.PutUint32(row[24:], uint32(len(name)))
		data = append(data, []byte(name)...)
		data = append(data, 0)
	}
	for i, name := range refs {
		row := data[48+48*len(names)+16*i:]
		le.PutUint32(row, uint32(len(data)))
		le.PutUint32(row[8:], uint32(len(name)))
		data = append(data, []byte(name)...)
		data = append(data, 0)
	}
	for i, name := range names {
		row := data[48+48*i:]
		le.PutUint32(row, uint32(len(data)))
		le.PutUint32(row[8:], uint32(len(members[name])))
		data = append(data, members[name]...)
	}
	le.PutUint32(data[10:], uint32(len(data)))
	return data
}

func syntheticQAR(t *testing.T, version uint32, compressed, encrypted bool, payload []byte) []byte {
	t.Helper()
	entry := qar.Entry{Header: qar.EntryHeader{FilePath: rootPack, Version: version, Compressed: compressed}, Data: payload}
	if encrypted {
		entry.DataHeader.Key = 1234
	}
	encoded, err := entry.Write()
	if err != nil {
		t.Fatal(err)
	}
	size := (1024 + len(encoded) + 1023) / 1024 * 1024
	data := make([]byte, size)
	copy(data, "SQAR")
	for offset, value := range map[int]uint32{4: 0 ^ 0x41441043, 8: 1 ^ 0x11C22050, 12: 0 ^ 0xD05608C3,
		16: uint32(size/1024) ^ 0x532C7319, 20: 1024 ^ 0x41441043, 24: version ^ 0x41441043, 28: 0 ^ 0x11C22050} {
		le.PutUint32(data[offset:], value)
	}
	section := uint64(1)<<40 | (entry.Header.PathHash&0xFF)<<32 | entry.Header.PathHash>>32&0xFFFFFFFFFF
	archive := qar.Qar{Version: version, FileCount: 1}
	sections, err := archive.EncryptSections([]uint64{section})
	if err != nil {
		t.Fatal(err)
	}
	copy(data[32:], sections)
	copy(data[1024:], encoded)
	return data
}

